SCRIPT = '''"""Generated by launch.py. Edit the repo, not this file."""
import os
import subprocess
import sys

os.environ.update({env!r})

# Kaggle Secrets, never a literal. Absent is fine; it only gates the HF push.
try:
    from kaggle_secrets import UserSecretsClient

    os.environ["HF_TOKEN"] = UserSecretsClient().get_secret("HF_TOKEN")
    print("HF_TOKEN loaded from Kaggle Secrets")
except Exception as exc:
    print(f"no HF_TOKEN ({{type(exc).__name__}}), skipping the Hub push")

subprocess.run(["rm", "-rf", "/kaggle/working/code"], check=False)
subprocess.run(["git", "clone", "--depth", "1", "-q", {repo!r},
                "/kaggle/working/code"], check=True)

code = subprocess.call(["bash", "/kaggle/working/code/kaggle_run.sh",
                        {hours!r}, {base!r}, {tokens!r}])
sys.exit(code)
'''


def have(cmd: str) -> bool:
    return shutil.which(cmd) is not None


def creds_path() -> Path:
    if os.environ.get("KAGGLE_CONFIG_DIR"):
        return Path(os.environ["KAGGLE_CONFIG_DIR"]) / "kaggle.json"
    return Path.home() / ".kaggle" / "kaggle.json"


def preflight(user_override: str = "") -> str:
    """Return the Kaggle username, or exit explaining exactly what is missing.

    Three auth styles are all valid and the CLI accepts any of them, so try in
    the order that asks least of you:
      * kaggle.json, the classic file, which carries the username
      * $KAGGLE_API_TOKEN or ~/.kaggle/access_token, the newer bare token,
        which does not, so the username is read back from the API
      * `kaggle auth login`, OAuth, which caches its own credentials
    """
    if not have("kaggle"):
        raise SystemExit(
            "the kaggle CLI is not installed.\n"
            "  pip install kaggle\n"
            "then rerun this.")
    if user_override:
        return user_override

    path = creds_path()
    if path.exists():
        try:
            return json.loads(path.read_text())["username"]
        except Exception as exc:
            raise SystemExit(f"{path} is not valid Kaggle credentials: {exc}")

    # A bare token authenticates fine but does not say who you are, and the
    # kernel id has to be "username/slug". Read it back off your own kernels.
    if os.environ.get("KAGGLE_API_TOKEN") or (path.parent / "access_token").exists():
        proc = subprocess.run(["kaggle", "kernels", "list", "-m", "--csv"],
                              capture_output=True, text=True)
        for line in proc.stdout.splitlines()[1:]:
            ref = line.split(",")[0].strip()
            if "/" in ref:
                return ref.split("/")[0]
        raise SystemExit(
            "the token authenticates but you have no kernels yet, so the "
            "username cannot be read back from it. Pass --user YOURNAME once.")

    raise SystemExit(
        "no Kaggle credentials found. Any one of these works:\n"
        "  kaggle auth login              OAuth, nothing to store\n"
        "  export KAGGLE_API_TOKEN=...    token from Settings -> API\n"
        f"  {path}                        Create New Token downloads it\n"
        "\nWhile you are in Settings, check Phone Verification is done. Without "
        "it the accelerator dropdown is greyed out and runs silently fall back "
        "to CPU, which trains fine and uselessly slowly.")


def run(cmd: list[str], check: bool = True) -> subprocess.CompletedProcess:
    print("$", " ".join(cmd))
    proc = subprocess.run(cmd, capture_output=True, text=True)
    for stream, out in ((proc.stdout, sys.stdout), (proc.stderr, sys.stderr)):
        if stream:
            print(stream.rstrip(), file=out)
    if check and proc.returncode != 0:
        raise SystemExit(proc.returncode)
    return proc


def write_kernel(work: Path, user: str, slug: str, spec: dict, private: bool) -> None:
    work.mkdir(parents=True, exist_ok=True)
    env = {"DEVICE": spec["device"], "MONITOR": "1", **spec["env"]}
    (work / "run.py").write_text(
        SCRIPT.format(env=env, repo=REPO, hours=spec["hours"],
                      base=spec["base"], tokens=spec["tokens"]),
        encoding="utf-8", newline="\n")
    (work / "kernel-metadata.json").write_text(json.dumps({
        "id": f"{user}/{slug}",
        "title": slug,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": "true" if private else "false",
        # Needed for the base download, the dataset stream and pip.
        "enable_internet": "true",
        "enable_gpu": "true" if spec["device"] == "gpu" else "false",
        "dataset_sources": [],
        "competition_sources": [],
        "kernel_sources": [],
        "model_sources": [],
    }, indent=1), encoding="utf-8", newline="\n")


def push(work: Path, accelerators: tuple[str, ...]) -> None:
    """Try each accelerator id in turn. Kaggle rotates them without notice."""
    last = None
    for acc in accelerators:
        print(f"\npushing with --accelerator {acc}")
        proc = run(["kaggle", "kernels", "push", "-p", str(work),
                    "--accelerator", acc], check=False)
        if proc.returncode == 0:
            return
        last = proc
        print(f"  {acc} rejected, trying the next id")
    raise SystemExit(
        "every accelerator id was rejected. Two usual causes: the account is "
        "not phone-verified, or Kaggle renamed the ids again. Check "
        "`kaggle kernels push --help` for the current list."
        + (f"\n\nlast error:\n{last.stderr}" if last and last.stderr else ""))


