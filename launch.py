def cmd_run(args: argparse.Namespace) -> None:
    spec = RUNS[args.what]
    user = preflight(getattr(args, 'user', ''))
    slug = args.slug or f"llm-reverse-{args.what}"
    work = Path(args.work_dir) / slug

    print(f"about to start:  {args.what}")
    print(f"  base       {spec['base']}")
    print(f"  device     {spec['device']}")
    print(f"  budget     {spec['hours']}h, {spec['tokens']} tokens")
    print(f"  kernel     {user}/{slug}")
    print(f"  why        {spec['why']}")
    if args.what.startswith("shakedown"):
        print("\n  it proves, in order:")
        for i, line in enumerate(PROVES, 1):
            print(f"    {i}. {line}")
        print(f"\n  and specifically: {spec['extra']}")
    else:
        print(f"\n  {spec['extra']}")
    print(f"\nThis consumes roughly {spec['hours']} hours of your weekly "
          f"{spec['device'].upper()} quota.")

    if not args.yes:
        reply = input("\ntype 'go' to push it: ").strip().lower()
        if reply != "go":
            print("not pushed")
            return

    write_kernel(work, user, slug, spec, private=not args.public)
    push(work, TPU_IDS if spec["device"] == "tpu" else GPU_IDS)

    url = f"https://www.kaggle.com/code/{user}/{slug}"
    print(f"\nrunning: {url}")
    print(f"  python launch.py status --slug {slug}")
    print(f"  python launch.py fetch  --slug {slug}")
    print("\nIt runs on Kaggle's servers. Your machine can sleep.")


def cmd_explain(args: argparse.Namespace) -> None:
    print("A shakedown proves, in order:\n")
    for i, line in enumerate(PROVES, 1):
        print(f"  {i}. {line}")
    print("\n2e7 tokens reaches every one of them. Bigger only buys a better "
          "loss curve\non a model you are going to throw away.\n")
    for name, spec in RUNS.items():
        print(f"--- {name}")
        print(f"    base {spec['base']}, {spec['device']}, {spec['hours']}h, "
              f"{spec['tokens']} tokens")
        print(f"    {spec['why']}")
        print(f"    {spec['extra']}\n")


def cmd_status(args: argparse.Namespace) -> None:
    user = preflight(getattr(args, 'user', ''))
    slug = args.slug or "llm-reverse-train"
    run(["kaggle", "kernels", "status", f"{user}/{slug}"], check=False)
    print(f"\nfull log: https://www.kaggle.com/code/{user}/{slug}")


def cmd_fetch(args: argparse.Namespace) -> None:
    user = preflight(getattr(args, 'user', ''))
    slug = args.slug or "llm-reverse-train"
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    run(["kaggle", "kernels", "output", f"{user}/{slug}", "-p", str(out)],
        check=False)
    gguf = sorted(out.rglob("*.gguf"))
    print(f"\ndownloaded to {out}")
    if gguf:
        g = gguf[0]
        print(f"\n  cd {g.parent} && ollama create llm-reverse -f Modelfile")
        print("  ollama run llm-reverse \"\"     # reads right to left")
    else:
        print("no .gguf yet. If the run is still going, wait; if it finished "
              "early, the checkpoints are still in the output and you can "
              "export locally with publish_hf.py.")


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="cmd", required=True)

    for name in RUNS:
        s = sub.add_parser(name, help=RUNS[name]["why"][:60])
        s.add_argument("--slug", default="")
        s.add_argument("--user", default="")
        s.add_argument("--work-dir", default=".launch")
        s.add_argument("--public", action="store_true")
        s.add_argument("--yes", action="store_true", help="skip the confirmation")
        s.set_defaults(func=cmd_run, what=name)

    s = sub.add_parser("explain", help="what each run does, without pushing")
    s.set_defaults(func=cmd_explain)

    s = sub.add_parser("status")
    s.add_argument("--slug", default="")
    s.add_argument("--user", default="")
    s.set_defaults(func=cmd_status)

    s = sub.add_parser("fetch")
    s.add_argument("--slug", default="")
    s.add_argument("--user", default="")
    s.add_argument("--out", default="downloaded")
    s.set_defaults(func=cmd_fetch)

    args = p.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
